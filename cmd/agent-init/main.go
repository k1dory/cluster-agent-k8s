// agent-init runs once per pod: generates a key, obtains the identity certificate from the
// Registrar and writes the client-certificate configuration every HTTP client in the image
// reads. The private key lives only in the tmpfs mounted at $CERT_DIR.
package main

import (
	"bytes"
	"crypto/tls"
	"crypto/x509"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"time"

	"agent-sandbox/internal/ca"
	"agent-sandbox/internal/registrar"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "agent-init:", err)
		os.Exit(1)
	}
}

func env(k, def string) string {
	if v := os.Getenv(k); v != "" {
		return v
	}
	return def
}

func run() error {
	certDir := env("CERT_DIR", "/certs")
	slug := env("SANDBOX_SLUG", "agent")
	registrarURL := os.Getenv("REGISTRAR_URL")
	if registrarURL == "" {
		return fmt.Errorf("REGISTRAR_URL is not set")
	}
	tokenPath := env("BOOTSTRAP_TOKEN_FILE", "/var/run/secrets/tokens/bootstrap")
	token, err := os.ReadFile(tokenPath)
	if err != nil {
		return fmt.Errorf("bootstrap token: %w", err)
	}

	keyPEM, csrPEM, err := ca.NewCSR(slug)
	if err != nil {
		return err
	}
	body, _ := json.Marshal(registrar.BootstrapRequest{CSR: string(csrPEM)})

	// The bootstrap endpoint sits behind the gateway's internal CA. sandboxd publishes that root
	// into a ConfigMap mounted at $GATEWAY_CA_FILE (and the compose/VM layout can bake it into the
	// image at $GATEWAY_CA_FILE too); without it only the system store is trusted, which fails
	// against an internal CA, and the error says so.
	// The root is published asynchronously and the ConfigMap mount is optional, so it may show
	// up after the first attempts: the trust store is rebuilt from the file on every attempt.
	caFile := env("GATEWAY_CA_FILE", "/etc/sandbox/gateway-ca/gateway-ca.crt")
	trust := func() (*http.Client, error) {
		client := &http.Client{Timeout: 30 * time.Second}
		pemBytes, err := os.ReadFile(caFile)
		if err != nil || len(bytes.TrimSpace(pemBytes)) == 0 {
			fmt.Fprintln(os.Stderr, "agent-init: no gateway root at", caFile, "(GATEWAY_CA_FILE) yet; trying the system store")
			return client, nil
		}
		pool := x509.NewCertPool()
		if !pool.AppendCertsFromPEM(pemBytes) {
			return nil, fmt.Errorf("%s is not a PEM certificate", caFile)
		}
		client.Transport = &http.Transport{TLSClientConfig: &tls.Config{RootCAs: pool, MinVersion: tls.VersionTLS12}}
		return client, nil
	}
	var res registrar.BootstrapResponse
	var lastErr error
	for attempt := 1; attempt <= 10; attempt++ {
		client, err := trust()
		if err != nil {
			return err
		}
		req, _ := http.NewRequest(http.MethodPost, strings.TrimRight(registrarURL, "/")+"/bootstrap", bytes.NewReader(body))
		req.Header.Set("Authorization", "Bearer "+strings.TrimSpace(string(token)))
		req.Header.Set("Content-Type", "application/json")
		resp, err := client.Do(req)
		if err != nil {
			lastErr = err
		} else {
			data, _ := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
			resp.Body.Close()
			if resp.StatusCode == http.StatusOK {
				if err := json.Unmarshal(data, &res); err != nil {
					return fmt.Errorf("bootstrap response: %w", err)
				}
				lastErr = nil
				break
			}
			lastErr = fmt.Errorf("bootstrap: %s: %s", resp.Status, strings.TrimSpace(string(data)))
			if resp.StatusCode == http.StatusUnauthorized || resp.StatusCode == http.StatusBadRequest {
				return lastErr
			}
		}
		time.Sleep(time.Duration(min(attempt, 5)) * 500 * time.Millisecond)
	}
	if lastErr != nil {
		return lastErr
	}

	if err := os.MkdirAll(certDir, 0o700); err != nil {
		return err
	}
	files := map[string]string{
		"tls.key":        string(keyPEM),
		"tls.crt":        res.Cert,
		"agent-ca.crt":   res.CA,
		"gateway-ca.crt": res.GatewayCA,
		"instance":       fmt.Sprintf("%d\n", res.Instance),
	}
	for name, content := range files {
		mode := os.FileMode(0o644)
		if name == "tls.key" {
			mode = 0o600
		}
		if err := os.WriteFile(filepath.Join(certDir, name), []byte(content), mode); err != nil {
			return err
		}
	}
	key, crt, gw := filepath.Join(certDir, "tls.key"), filepath.Join(certDir, "tls.crt"), filepath.Join(certDir, "gateway-ca.crt")

	// Environment every process in the agent container sources (see images/agent/profile.sh).
	envSh := fmt.Sprintf(`# generated by agent-init; identity %s/%d
export SANDBOX_INSTANCE=%d
export GIT_SSL_CERT=%s
export GIT_SSL_KEY=%s
export GIT_SSL_CAINFO=%s
export SSL_CERT_FILE=%s
export REQUESTS_CA_BUNDLE=%s
export CURL_CA_BUNDLE=%s
export NODE_EXTRA_CA_CERTS=%s
export SANDBOX_CLIENT_CERT=%s
export SANDBOX_CLIENT_KEY=%s
# Claude Code's own mTLS settings (https://code.claude.com/docs/en/network-config#mtls-authentication)
export CLAUDE_CODE_CLIENT_CERT=%s
export CLAUDE_CODE_CLIENT_KEY=%s
`, res.Slug, res.Instance, res.Instance, crt, key, gw, gw, gw, gw, gw, crt, key, crt, key)
	if err := os.WriteFile(filepath.Join(certDir, "env.sh"), []byte(envSh), 0o644); err != nil {
		return err
	}
	// curl has no env var for the client cert: a config file in the cert dir, referenced by CURL_HOME.
	curlrc := fmt.Sprintf("cert = %s\nkey = %s\ncacert = %s\n", crt, key, gw)
	if err := os.WriteFile(filepath.Join(certDir, ".curlrc"), []byte(curlrc), 0o644); err != nil {
		return err
	}
	// git: config file picked up via GIT_CONFIG_GLOBAL (set in the image).
	gitcfg := fmt.Sprintf("[http]\n\tsslCert = %s\n\tsslKey = %s\n\tsslCAInfo = %s\n[user]\n\tname = %s #%d\n\temail = %s-%d@agent.sandbox\n",
		crt, key, gw, res.Slug, res.Instance, res.Slug, res.Instance)
	if err := os.WriteFile(filepath.Join(certDir, "gitconfig"), []byte(gitcfg), 0o644); err != nil {
		return err
	}
	fmt.Printf("agent-init: identity %s/%d issued, valid until %s\n", res.Slug, res.Instance, res.NotAfter.Format(time.RFC3339))
	return nil
}
