// Package gateway turns policies into the running gateway: it renders the Caddy
// configuration, pushes it through Caddy's admin API, fetches Caddy's internal root for
// the pods and answers DNS for the allowlisted names. Nobody edits the Caddyfile by hand.
package gateway

import (
	"bytes"
	"context"
	"encoding/base64"
	"encoding/json"
	"encoding/pem"
	"errors"
	"fmt"
	"io"
	"log/slog"
	"net/http"
	"os"
	"sort"
	"strings"
	"text/template"
	"time"

	"agent-sandbox/internal/policy"
)

// Config describes the gateway sandboxd drives.
type Config struct {
	IP         string // address on the sandbox VLAN, e.g. 10.77.77.1
	Bind       string // Caddy default_bind; "" = all interfaces (tests bind 127.0.0.1)
	HTTPSPort  int    // Caddy https_port; 0 = 443
	HTTPPort   int    // Caddy http_port; 0 = 80
	CaddyAdmin string // http://127.0.0.1:2019; "" = render only
	// RootCert / RootKey: PEM files Caddy's internal CA must use as its root instead of generating
	// one, so every replica's gateway presents certificates the pods trust (sandboxd writes the
	// shared root there when ca.source is db).
	RootCert      string
	RootKey       string
	CaddyfileOut  string // where to write the rendered Caddyfile for inspection ("" = don't)
	SandboxdAddr  string // Caddy → sandboxd gateway listener, e.g. 127.0.0.1:8081
	IngressAddr   string // Caddy → sandboxd preview listener, e.g. 127.0.0.1:8082
	APIHost       string // agent-facing API name, e.g. api.sandbox.internal
	RegistrarHost string // bootstrap name, e.g. registrar.sandbox.internal
	RegistrarPort int    // 8443
	PreviewDomain string // preview.example.com ("" disables the preview site)
	PreviewTLS    string // extra tls directive body for the preview wildcard, e.g. "dns cloudflare {env.CF_TOKEN}"; "" = on_demand
	AccessLog     string // file path or "stdout"
	StrictSNI     bool
}

// InternalHosts are names served by the gateway itself and must resolve too.
func (c Config) InternalHosts() []string {
	var out []string
	if c.APIHost != "" {
		out = append(out, c.APIHost)
	}
	if c.RegistrarHost != "" {
		out = append(out, c.RegistrarHost)
	}
	return out
}

// Headers the gateway copies from the authz response onto the upstream request.
var copyHeaders = []string{"X-Agent-Slug", "X-Agent-Instance", "X-Agent-Tenant", "X-Agent-Sandbox", "X-Agent-Access"}

const caddyfileTmpl = `# GENERATED by sandboxd from policies at {{ .Now }}. Do not edit: changes are overwritten on the next policy reload.
#
# Every site uses an explicit route{} so the order is what you read, not Caddy's directive
# order (which would run forward_auth before request_header): strip what the agent sent in
# protected headers, ask sandboxd, copy its verdict headers (identity + injected secrets)
# onto the request, proxy.
{
	skip_install_trust
	admin {{ .Admin }}
{{- if .Bind }}
	default_bind {{ .Bind }}
{{- end }}
{{- if .HTTPSPort }}
	https_port {{ .HTTPSPort }}
{{- end }}
{{- if .HTTPPort }}
	http_port {{ .HTTPPort }}
{{- end }}
	pki {
		ca local {
			name "agent-sandbox gateway"
{{- if .RootCert }}
			root {
				cert {{ .RootCert }}
				key {{ .RootKey }}
			}
{{- end }}
		}
	}
{{- if .StrictSNI }}
	servers {
		strict_sni_host on
	}
{{- end }}
	log {
{{- if or (eq .AccessLog "stdout") (eq .AccessLog "stderr") }}
		output {{ .AccessLog }}
{{- else }}
		output file {{ .AccessLog }} {
			roll_size 100mb
			roll_keep 30
		}
{{- end }}
		format json
	}
{{- if .PreviewDomain }}
	on_demand_tls {
		ask http://{{ .IngressAddr }}/__sandbox/ask
	}
{{- end }}
}

(agent_mtls) {
	tls {
		issuer internal
		client_auth {
			mode require_and_verify
			trust_pool inline {
				trust_der {{ .AgentCAB64 }}
			}
		}
	}
}
{{ range .Hosts }}
# policy host: {{ .Name }}
{{ .Name }} {
	import agent_mtls
	route {
		# the agent must not be able to forge identity headers or pre-set injected ones
{{- range .Strip }}
		request_header -{{ . }}
{{- end }}
		forward_auth {{ $.SandboxdAddr }} {
			uri /authz
			header_up X-Agent-Cert {http.request.tls.client.certificate_der_base64}
			header_up X-Agent-SAN {http.request.tls.client.san.uris}
			copy_headers {{ .Copy }}
		}
{{- if .MCP }}
		# MCP endpoint: sandboxd inspects the JSON-RPC body (tools/call allowlist) and forwards to
		# the upstream its policy names for this host (the Host header Caddy validated by SNI)
		reverse_proxy {{ $.SandboxdAddr }} {
			header_up X-Agent-Cert {http.request.tls.client.certificate_der_base64}
			header_up X-Agent-SAN {http.request.tls.client.san.uris}
			flush_interval -1
		}
{{- else }}
		reverse_proxy {{ .Upstream }} {
{{- if .TLSServerName }}
			transport http {
				tls_server_name {{ .TLSServerName }}
			}
{{- end }}
			flush_interval -1
		}
{{- end }}
	}
}
{{ end }}
{{- if .APIHost }}
# agent-facing control plane API (runs, output, input): identity from the client certificate,
# checked by sandboxd itself (no policy lookup: every agent may talk to its control plane)
{{ .APIHost }} {
	import agent_mtls
	route {
		request_header -X-Agent-Cert
		request_header -X-Agent-SAN
		request_header -X-Sandbox-Mcp-Upstream
		request_header -X-Sandbox-Mcp-Host
		reverse_proxy {{ .SandboxdAddr }} {
			header_up X-Agent-Cert {http.request.tls.client.certificate_der_base64}
			header_up X-Agent-SAN {http.request.tls.client.san.uris}
			flush_interval -1
		}
	}
}
{{ end }}
{{- if .RegistrarHost }}
# bootstrap: the only endpoint reachable without a client certificate
{{ .RegistrarHost }}:{{ .RegistrarPort }} {
	tls {
		issuer internal
	}
	@bootstrap {
		method POST
		path /bootstrap
	}
	handle @bootstrap {
		reverse_proxy {{ .SandboxdAddr }}
	}
	handle {
		respond 404
	}
}
{{ end }}
{{- if .PreviewDomain }}
# preview: outside world → application inside the sandbox
*.{{ .PreviewDomain }} {
	tls {
{{- if .PreviewTLS }}
		{{ .PreviewTLS }}
{{- else }}
		on_demand
{{- end }}
	}
	reverse_proxy {{ .IngressAddr }} {
		flush_interval -1
	}
}
{{ end }}
`

type hostView struct {
	Name, Upstream, TLSServerName string
	MCP                           bool
	Strip                         []string // headers removed from the agent's request
	Copy                          string   // headers copied from the authz response (space-separated)
}

type view struct {
	Now, Admin, AccessLog, AgentCAB64                 string
	RootCert, RootKey                                 string
	Bind                                              string
	HTTPSPort, HTTPPort                               int
	SandboxdAddr, IngressAddr, APIHost, RegistrarHost string
	RegistrarPort                                     int
	PreviewDomain, PreviewTLS                         string
	StrictSNI                                         bool
	Hosts                                             []hostView
}

// Render produces the Caddyfile for the given policies and agent CA root (PEM).
func Render(cfg Config, hosts []policy.Host, agentCAPEM []byte) (string, error) {
	blk, _ := pem.Decode(agentCAPEM)
	if blk == nil {
		return "", errors.New("agent CA: no PEM certificate")
	}
	admin := "off"
	if cfg.CaddyAdmin != "" {
		admin = strings.TrimPrefix(strings.TrimPrefix(cfg.CaddyAdmin, "http://"), "https://")
	}
	accessLog := cfg.AccessLog
	if accessLog == "" {
		accessLog = "stdout"
	}
	v := view{
		Now: time.Now().UTC().Format(time.RFC3339), Admin: admin, AccessLog: accessLog,
		AgentCAB64: base64.StdEncoding.EncodeToString(blk.Bytes),
		Bind:       cfg.Bind, HTTPSPort: cfg.HTTPSPort, HTTPPort: cfg.HTTPPort, RootCert: cfg.RootCert, RootKey: cfg.RootKey,
		SandboxdAddr: cfg.SandboxdAddr, IngressAddr: cfg.IngressAddr, APIHost: cfg.APIHost,
		RegistrarHost: cfg.RegistrarHost, RegistrarPort: cfg.RegistrarPort,
		PreviewDomain: cfg.PreviewDomain, PreviewTLS: cfg.PreviewTLS, StrictSNI: cfg.StrictSNI,
	}
	if v.RegistrarPort == 0 {
		v.RegistrarPort = 8443
	}
	for _, h := range hosts {
		if h.Name == cfg.APIHost || h.Name == cfg.RegistrarHost {
			continue // served by the built-in blocks
		}
		hv := hostView{Name: h.Name, Upstream: h.Upstream, MCP: h.MCP}
		// Upstream by IP but TLS for the real name: tell the transport which SNI/verification name to use.
		if strings.HasPrefix(h.Upstream, "https://") {
			up := strings.TrimPrefix(h.Upstream, "https://")
			if i := strings.Index(up, "/"); i >= 0 {
				up = up[:i]
			}
			if i := strings.LastIndex(up, ":"); i >= 0 {
				up = up[:i]
			}
			if up != h.Name && isIP(up) {
				hv.TLSServerName = h.Name
			}
		}
		// Stripped before authz: the identity headers Caddy sets, the verdict headers it copies
		// and every header the policy injects, so an agent can neither forge an identity nor
		// pre-set a secret. Copied after authz: the verdict headers plus the injected ones.
		hv.Strip = append([]string{"X-Agent-Cert", "X-Agent-SAN", "X-Sandbox-Mcp-Upstream", "X-Sandbox-Mcp-Host"}, copyHeaders...)
		hv.Strip = append(hv.Strip, h.Injected...)
		hv.Copy = strings.Join(append(append([]string{}, copyHeaders...), h.Injected...), " ")
		v.Hosts = append(v.Hosts, hv)
	}
	t := template.Must(template.New("caddyfile").Parse(caddyfileTmpl))
	var buf bytes.Buffer
	if err := t.Execute(&buf, v); err != nil {
		return "", err
	}
	return buf.String(), nil
}

func isIP(s string) bool {
	for _, r := range s {
		if (r < '0' || r > '9') && r != '.' {
			return false
		}
	}
	return s != ""
}

// Push loads the Caddyfile into a running Caddy through its admin API.
func Push(ctx context.Context, adminURL, caddyfile string) error {
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, strings.TrimRight(adminURL, "/")+"/load", strings.NewReader(caddyfile))
	if err != nil {
		return err
	}
	req.Header.Set("Content-Type", "text/caddyfile")
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return fmt.Errorf("caddy admin: %w", err)
	}
	defer resp.Body.Close()
	body, _ := io.ReadAll(io.LimitReader(resp.Body, 64<<10))
	if resp.StatusCode >= 300 {
		return fmt.Errorf("caddy admin /load: %s: %s", resp.Status, strings.TrimSpace(string(body)))
	}
	return nil
}

// FetchRoot returns Caddy's internal CA root certificate (PEM), the one pods must trust.
func FetchRoot(ctx context.Context, adminURL string) ([]byte, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, strings.TrimRight(adminURL, "/")+"/pki/ca/local", nil)
	if err != nil {
		return nil, err
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, fmt.Errorf("caddy admin: %w", err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		body, _ := io.ReadAll(io.LimitReader(resp.Body, 4<<10))
		return nil, fmt.Errorf("caddy admin /pki/ca/local: %s: %s", resp.Status, strings.TrimSpace(string(body)))
	}
	var out struct {
		Root string `json:"root_certificate"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&out); err != nil {
		return nil, err
	}
	if out.Root == "" {
		return nil, errors.New("caddy returned no root certificate")
	}
	return []byte(out.Root), nil
}

// HeaderSource adds header names the gateway must strip from agent requests and copy from the
// decision, per host, beyond what policies inject (the connections service). The fingerprint
// changes when the list does.
type HeaderSource interface {
	HostHeaders() (map[string][]string, string)
}

// HostLister is where the gateway's hosts come from: the policy set alone, or the guard that
// adds the hosts live connections serve on their own (bindings.Guard).
type HostLister interface {
	Hosts() []policy.Host
	Fingerprint() string
}

// Syncer keeps Caddy in step with the policy set (and the connections' header names).
type Syncer struct {
	Cfg      Config
	Policies HostLister
	Headers  HeaderSource // optional
	AgentCA  []byte
	Log      *slog.Logger
	last     string
}

// hosts is the policy set's host list with the extra header names merged in.
func (s *Syncer) hosts() ([]policy.Host, string) {
	hs, fp := s.Policies.Hosts(), s.Policies.Fingerprint()
	if s.Headers == nil {
		return hs, fp
	}
	extra, efp := s.Headers.HostHeaders()
	for i := range hs {
		for _, name := range extra[hs[i].Name] {
			hs[i].Injected = appendUnique(hs[i].Injected, name)
		}
		sort.Strings(hs[i].Injected)
	}
	return hs, fp + "+" + efp
}

func appendUnique(xs []string, x string) []string {
	for _, y := range xs {
		if y == x {
			return xs
		}
	}
	return append(xs, x)
}

// SyncOnce renders and (if configured) pushes the config when policies or connection header
// names changed since last time.
func (s *Syncer) SyncOnce(ctx context.Context, force bool) error {
	hs, fp := s.hosts()
	if !force && fp == s.last {
		return nil
	}
	cf, err := Render(s.Cfg, hs, s.AgentCA)
	if err != nil {
		return err
	}
	if s.Cfg.CaddyfileOut != "" {
		if err := os.WriteFile(s.Cfg.CaddyfileOut, []byte(cf), 0o644); err != nil {
			return err
		}
	}
	if s.Cfg.CaddyAdmin != "" {
		if err := Push(ctx, s.Cfg.CaddyAdmin, cf); err != nil {
			return err
		}
	}
	s.last = fp
	if s.Log != nil {
		s.Log.Info("gateway config synced", "hosts", len(s.Policies.Hosts()), "pushed", s.Cfg.CaddyAdmin != "")
	}
	return nil
}

// Run syncs now, then re-syncs whenever policies change, until ctx ends.
func (s *Syncer) Run(ctx context.Context, every time.Duration) {
	for attempt := 1; ; attempt++ {
		if err := s.SyncOnce(ctx, true); err == nil {
			break
		} else if s.Log != nil {
			s.Log.Error("gateway sync", "attempt", attempt, "err", err)
		}
		select {
		case <-ctx.Done():
			return
		case <-time.After(time.Duration(min(attempt, 12)) * 5 * time.Second):
		}
	}
	t := time.NewTicker(every)
	defer t.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-t.C:
			if err := s.SyncOnce(ctx, false); err != nil && s.Log != nil {
				s.Log.Error("gateway sync", "err", err)
			}
		}
	}
}
