// Config describes the gateway sandboxd drives.
type Config struct {
	IP         string // address on the sandbox VLAN, e.g. 10.77.77.1
	Bind       string // Caddy default_bind; "" = all interfaces (tests bind 127.0.0.1)
	HTTPSPort  int    // Caddy https_port; 0 = 443
	HTTPPort   int    // Caddy http_port; 0 = 80
	CaddyAdmin string // http://127.0.0.1:2019; "" = render only
	// RootCert / RootKey: PEM files Caddy's internal CA must use as its root instead of generating
	// one, so every replica's gateway presents certificates the pods trust (sandboxd writes the
	// shared root there when ca.source is db).
	RootCert      string
	RootKey       string
	CaddyfileOut  string // where to write the rendered Caddyfile for inspection ("" = don't)
	SandboxdAddr  string // Caddy → sandboxd gateway listener, e.g. 127.0.0.1:8081
	IngressAddr   string // Caddy → sandboxd preview listener, e.g. 127.0.0.1:8082
	APIHost       string // agent-facing API name, e.g. api.sandbox.internal
	RegistrarHost string // bootstrap name, e.g. registrar.sandbox.internal
	RegistrarPort int    // 8443
	PreviewDomain string // preview.example.com ("" disables the preview site)
	PreviewTLS    string // extra tls directive body for the preview wildcard, e.g. "dns cloudflare {env.CF_TOKEN}"; "" = on_demand
	AccessLog     string // file path or "stdout"
	StrictSNI     bool
}

// InternalHosts are names served by the gateway itself and must resolve too.
func (c Config) InternalHosts() []string {
	var out []string
	if c.APIHost != "" {
		out = append(out, c.APIHost)
	}
	if c.RegistrarHost != "" {
		out = append(out, c.RegistrarHost)
	}
	return out
}

// Headers the gateway copies from the authz response onto the upstream request.
var copyHeaders = []string{"X-Agent-Slug", "X-Agent-Instance", "X-Agent-Tenant", "X-Agent-Sandbox", "X-Agent-Access"}

